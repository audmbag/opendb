import type { BaseModel } from '@/types/models/base-model';

export enum DefaultDrivers {
    MYSQL = 'mysql',
    SQLITE = 'sqlite',
    MARIADB = 'mariadb',
    POSTGRESQL = 'pgsql',
}

export type Driver = {
    id: DefaultDrivers;
    name: string;
    icon?: string;
};


export interface SSHConfiguration {
    host: string;
    port: number;
    user: string;
    id_file: string;
}



export interface Table {
    name: string;
    columns: number;
    agentAccessEnabled: boolean;
    cloningIncludingEnabled: boolean;
}

export interface DriverConfig extends BaseModel<number> {
    driver?: Driver;
    driver_id?: string;
    host?: string;
    port?: number;
    database: string;
    username?: string;
    password?: string;
    connection_string?: string;
    ssh?: SSHConfiguration;
    create_database_if_not_exists?: boolean;
    tables_info?: Table[];
}

export type RecordFormFieldType =
    | 'string'
    | 'text'
    | 'integer'
    | 'decimal'
    | 'boolean'
    | 'date'
    | 'datetime'
    | 'time'
    | 'json'
    | 'uuid'
    | 'enum';

/**
 * A field of the form adding a row to a table, generated by TableRecordForm from one of its columns.
 */
export type RecordFormField = {
    name: string;
    type: RecordFormFieldType;
    db_type: string;
    required: boolean;
    nullable: boolean;
    default: string | null;
    max_length: number | null;
    options: string[] | null;
    unique: boolean;
    references: { table: string; column: string } | null;
};

export type RecordForm = {
    table: string;
    fields: RecordFormField[];
};
