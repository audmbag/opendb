<?php

declare(strict_types=1);

namespace App\Services\Cloning\Engine\SqlDump\Dialects;

use App\Services\Cloning\Engine\Data\Schema\ColumnSchemaData;
use App\Services\Cloning\Engine\Enums\DatabaseConnectionType;

class PostgreSqlDumpDialect extends AbstractDumpDialect
{
    protected function dialectDisplayName(): string
    {
        return 'PostgreSQL';
    }

    public function quoteIdentifier(string $name): string
    {
        return '"'.str_replace('"', '""', $name).'"';
    }

    protected function qualifiedTable(string $table): string
    {
        return $this->quoteIdentifier($table);
    }

    public function preamble(bool $disableFkChecks): string
    {
        return $disableFkChecks ? "SET session_replication_role = 'replica';\n\n" : '';
    }

    public function postamble(bool $disableFkChecks, array $tables): string
    {
        return $disableFkChecks ? "\nSET session_replication_role = 'origin';\n" : '';
    }

    protected function binaryLiteral(string $hex): string
    {
        return "E'\\\\x".$hex."'";
    }

    protected function booleanLiteral(bool $value): string
    {
        return $value ? 'TRUE' : 'FALSE';
    }

    protected function engine(): DatabaseConnectionType
    {
        return DatabaseConnectionType::PostgreSQL;
    }

    protected function mapColumnType(ColumnSchemaData $column, bool $inKey = false, ?DatabaseConnectionType $source = null): string
    {
        $unsigned = $column->unsigned;
        $fraction = $this->fractionalSeconds($column, $source);

        return match ($this->kind($column, $source)) {
            'boolean' => 'BOOLEAN',
            'tinyint' => 'SMALLINT',
            'smallint' => $unsigned ? 'INTEGER' : 'SMALLINT',
            'int' => $unsigned ? 'BIGINT' : 'INTEGER',
            'bigint' => $unsigned ? 'NUMERIC(20,0)' : 'BIGINT',
            'float' => 'REAL',
            'double' => 'DOUBLE PRECISION',
            'decimal' => $column->precision !== null && $column->precision > 0 ? 'NUMERIC('.$this->decimalSpec($column).')' : 'NUMERIC',
            'varchar' => $column->length !== null && $column->length > 0 ? 'VARCHAR('.$column->length.')' : 'TEXT',
            'char' => $column->length !== null && $column->length > 0 ? 'CHAR('.$column->length.')' : 'TEXT',
            'date' => 'DATE',
            'datetime', 'timestamp' => "TIMESTAMP({$fraction})",
            'timestamptz' => "TIMESTAMPTZ({$fraction})",
            'time' => "TIME({$fraction})",
            'year' => 'SMALLINT',
            'json' => 'JSONB',
            'blob' => 'BYTEA',
            'uuid' => 'UUID',
            default => 'TEXT',
        };
    }

    protected function defaultBoolean(bool $value, string $type): string
    {
        return preg_match('/^bool/i', $type) === 1 ? ($value ? 'TRUE' : 'FALSE') : ($value ? "'1'" : "'0'");
    }

    /**
     * Ajoutée NOT VALID, la clé ne relit pas les lignes copiées ; elle vérifie celles écrites ensuite.
     */
    protected function unvalidatedConstraint(): string
    {
        return ' NOT VALID';
    }

    protected function identityType(string $type): ?string
    {
        return preg_match('/^(smallint|integer|int|bigint)$/i', $type) === 1 ? $type.' GENERATED BY DEFAULT AS IDENTITY' : null;
    }
}
