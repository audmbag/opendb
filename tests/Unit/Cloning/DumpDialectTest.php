<?php

use App\Services\Cloning\Engine\Data\Schema\ColumnDefaultData;
use App\Services\Cloning\Engine\Data\Schema\ColumnSchemaData;
use App\Services\Cloning\Engine\Data\Schema\ForeignKeyConstraintData;
use App\Services\Cloning\Engine\Data\Schema\IndexSchemaData;
use App\Services\Cloning\Engine\Data\Schema\TableSchemaData;
use App\Services\Cloning\Engine\Enums\DatabaseConnectionType;
use App\Services\Cloning\Engine\SqlDump\Dialects\MySqlDumpDialect;
use App\Services\Cloning\Engine\SqlDump\Dialects\PostgreSqlDumpDialect;
use App\Services\Cloning\Engine\SqlDump\Dialects\SqliteDumpDialect;

/**
 * @param  list<ColumnSchemaData>  $columns
 * @param  list<IndexSchemaData>  $indexes
 */
function dumpTable(array $columns, array $indexes = [], array $primaryKey = ['id']): TableSchemaData
{
    return new TableSchemaData('authors', $columns, [], $indexes, $primaryKey);
}

function dumpColumn(string $name, string $type, ?string $declared = null, bool $primary = false, bool $autoIncrement = false, ?int $length = null, ?int $precision = null, ?int $scale = null, bool $unsigned = false): ColumnSchemaData
{
    return new ColumnSchemaData($name, $type, ! $primary, null, $primary, $unsigned, $length, $precision, $scale, $declared, $autoIncrement);
}

it('keeps the declared types of a table from the same database family', function () {
    $table = dumpTable([
        dumpColumn('id', 'int', 'int unsigned', primary: true, autoIncrement: true, unsigned: true),
        dumpColumn('price', 'decimal', 'decimal(15,4)', precision: 15, scale: 4),
        dumpColumn('mood', 'enum', "enum('happy','sad')"),
    ]);

    expect(new MySqlDumpDialect()->createTable($table, true, DatabaseConnectionType::MariaDB))
        ->toContain('`id` int unsigned AUTO_INCREMENT,')
        ->toContain('`price` decimal(15,4)')
        ->toContain("`mood` enum('happy','sad')")
        ->toContain('PRIMARY KEY (`id`)');
});

it('gives MySQL the lengths of a SQLite table and a length to the text it indexes', function () {
    $table = dumpTable([
        dumpColumn('id', 'integer', 'integer', primary: true, autoIncrement: true),
        dumpColumn('code', 'varchar', 'varchar(10)', length: 10),
        dumpColumn('email', 'varchar', 'varchar'),
        dumpColumn('bio', 'text', 'text'),
        dumpColumn('price', 'numeric', 'numeric(15,4)', precision: 15, scale: 4),
        dumpColumn('created_at', 'datetime', 'datetime'),
    ], [new IndexSchemaData('authors_email_unique', ['email'], true), new IndexSchemaData('authors_bio_index', ['bio'], false)]);
    $dialect = new MySqlDumpDialect;

    expect($dialect->createTable($table, true, DatabaseConnectionType::Sqlite))
        ->toContain('`id` BIGINT AUTO_INCREMENT,')
        ->toContain('`code` VARCHAR(10)')
        ->toContain('`email` VARCHAR(255)')
        ->toContain('`bio` LONGTEXT')
        ->toContain('`price` DECIMAL(15,4)')
        ->toContain('`created_at` DATETIME(6)')
        ->and($dialect->createIndexes($table, DatabaseConnectionType::Sqlite))->toBe([
            'CREATE UNIQUE INDEX `authors_email_unique` ON `authors` (`email`);',
            'CREATE INDEX `authors_bio_index` ON `authors` (`bio`(191));',
        ]);
});

it('writes a MySQL table with types PostgreSQL knows and index names unique in its schema', function () {
    $table = dumpTable([
        dumpColumn('id', 'int', 'int unsigned', primary: true, autoIncrement: true, unsigned: true),
        dumpColumn('rating', 'double', 'double'),
        dumpColumn('avatar', 'blob', 'blob'),
        dumpColumn('created_at', 'datetime', 'datetime(3)', length: 3),
        dumpColumn('author_id', 'int', 'int'),
    ], [new IndexSchemaData('author_id', ['author_id'], false)]);
    $dialect = new PostgreSqlDumpDialect;

    expect($dialect->createTable($table, true, DatabaseConnectionType::Mysql))
        ->toContain('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY,')
        ->toContain('"rating" DOUBLE PRECISION')
        ->toContain('"avatar" BYTEA')
        ->toContain('"created_at" TIMESTAMP(3)')
        ->and($dialect->createIndexes($table, DatabaseConnectionType::Mysql))->toBe(['CREATE INDEX "authors_author_id" ON "authors" ("author_id");']);
});

it('lets SQLite generate the key of an auto-incremented table', function () {
    $table = dumpTable([dumpColumn('id', 'integer', 'integer', primary: true, autoIncrement: true), dumpColumn('name', 'character varying', 'character varying(500)', length: 500)]);

    expect(new SqliteDumpDialect()->createTable($table, true, DatabaseConnectionType::PostgreSQL))
        ->toContain('"id" INTEGER PRIMARY KEY AUTOINCREMENT,')
        ->toContain('"name" VARCHAR(500)')
        ->not->toContain('PRIMARY KEY ("id")');
});

it('orders a composite primary key as its index does', function () {
    $table = dumpTable([dumpColumn('post_id', 'bigint', primary: true), dumpColumn('tag_slug', 'varchar', length: 64, primary: true)], primaryKey: ['tag_slug', 'post_id']);

    expect(new PostgreSqlDumpDialect()->createTable($table, true, DatabaseConnectionType::Mysql))->toContain('PRIMARY KEY ("tag_slug", "post_id")');
});

it('writes the portable defaults of another database and leaves out its own expressions', function () {
    $table = dumpTable([
        dumpColumn('id', 'integer', 'integer', primary: true, autoIncrement: true),
        new ColumnSchemaData('path', 'varchar', true, null, false, false, 255, null, null, 'varchar(255)', false, new ColumnDefaultData(ColumnDefaultData::VALUE, 'C:\temp')),
        new ColumnSchemaData('bio', 'text', true, null, false, defaultValue: new ColumnDefaultData(ColumnDefaultData::VALUE, "l'auteur")),
        new ColumnSchemaData('created_at', 'timestamp', true, null, false, declaredType: 'timestamp(3) without time zone', defaultValue: new ColumnDefaultData(ColumnDefaultData::CURRENT_TIMESTAMP, '')),
        new ColumnSchemaData('active', 'boolean', false, null, false, defaultValue: new ColumnDefaultData(ColumnDefaultData::BOOLEAN, '1')),
        new ColumnSchemaData('token', 'uuid', true, null, false, defaultValue: new ColumnDefaultData(ColumnDefaultData::EXPRESSION, 'gen_random_uuid()')),
    ]);
    $mysql = new MySqlDumpDialect;

    expect($mysql->createTable($table, true, DatabaseConnectionType::PostgreSQL))
        ->toContain("`path` VARCHAR(255) DEFAULT 'C:\\\\temp'")
        ->toContain("`bio` LONGTEXT DEFAULT ('l''auteur')")
        ->toContain('`created_at` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3)')
        ->toContain("`active` TINYINT(1) DEFAULT '1' NOT NULL")
        ->toContain('`token` CHAR(36),')
        ->and($mysql->unportableDefaults($table, DatabaseConnectionType::PostgreSQL))->toBe(['token'])
        ->and(new PostgreSqlDumpDialect()->createTable($table, true, DatabaseConnectionType::PostgreSQL))->toContain('"token" UUID DEFAULT gen_random_uuid()')
        ->and(new PostgreSqlDumpDialect()->createTable($table, true, DatabaseConnectionType::Sqlite))->toContain('"active" BOOLEAN DEFAULT TRUE NOT NULL');
});

it('adds foreign keys after the copy, or inside CREATE TABLE for SQLite', function () {
    $table = new TableSchemaData('post_tag', [dumpColumn('post_id', 'bigint', primary: true), dumpColumn('tag_slug', 'varchar', length: 64, primary: true)], [], [], ['tag_slug', 'post_id'], [
        new ForeignKeyConstraintData(null, ['post_id'], 'posts', ['id'], onDelete: 'CASCADE'),
        new ForeignKeyConstraintData('post_tag_tag_fk', ['tag_slug'], 'tags', null, onUpdate: 'SET DEFAULT'),
    ]);

    expect(new PostgreSqlDumpDialect()->addForeignKeys($table, DatabaseConnectionType::Sqlite)[0])
        ->toBe('ALTER TABLE "post_tag" ADD CONSTRAINT "post_tag_post_id_foreign" FOREIGN KEY ("post_id") REFERENCES "posts" ("id") ON DELETE CASCADE ON UPDATE NO ACTION NOT VALID;')
        ->and(new MySqlDumpDialect()->addForeignKeys($table, DatabaseConnectionType::PostgreSQL)[1])
        ->toBe('ALTER TABLE `post_tag` ADD CONSTRAINT `post_tag_tag_fk` FOREIGN KEY (`tag_slug`) REFERENCES `tags` ON DELETE NO ACTION ON UPDATE NO ACTION;')
        ->and(new SqliteDumpDialect()->addForeignKeys($table))->toBe([])
        ->and(new SqliteDumpDialect()->createTable($table, true, DatabaseConnectionType::Mysql))
        ->toContain('FOREIGN KEY ("post_id") REFERENCES "posts" ("id") ON DELETE CASCADE ON UPDATE NO ACTION');
});
